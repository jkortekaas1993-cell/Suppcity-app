import type { Equipment, MuscleGroup } from '@/lib/db/types';

/**
 * Seed data for the Dutch exercise library. `slug` is the stable key used by
 * programs.ts, CSV import mapping and sync; never rename a slug, only add.
 * Names and descriptions may be improved; slugs never change.
 *
 * Descriptions are short technique cues only: no health, performance or
 * product claims (hard rule 4 applies to anything that reads like a claim).
 */
export interface ExerciseSeed {
  slug: string;
  name_nl: string;
  primary_muscle: MuscleGroup;
  secondary_muscles: MuscleGroup[];
  equipment: Equipment;
  /** Names used by Hevy/Strong exports, for CSV import mapping. */
  aliases_en: string[];
  /** One or two sentences on how to perform the exercise. */
  description_nl: string;
}

function ex(
  slug: string,
  name_nl: string,
  primary_muscle: MuscleGroup,
  secondary_muscles: MuscleGroup[],
  equipment: Equipment,
  aliases_en: string[],
  description_nl: string,
): ExerciseSeed {
  return { slug, name_nl, primary_muscle, secondary_muscles, equipment, aliases_en, description_nl };
}

